import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { effectiveUsage, validatePreference } from "../lib/dish-preference-rules.mjs";
import { savePreference, preferenceContext, validateMealPreferences } from "./dish-preferences.mjs";
import { missingRecipeCoverage } from "../lib/recipe-coverage.mjs";

const db = new DatabaseSync(":memory:");
db.exec(`
CREATE TABLE Dish (id TEXT PRIMARY KEY, name TEXT, category TEXT, aliases TEXT, createdAt INTEGER, UNIQUE(name,category));
CREATE TABLE DishPreference (id TEXT PRIMARY KEY, dishId TEXT, scope TEXT, usage TEXT, familiarity TEXT, note TEXT, source TEXT, confirmedAt INTEGER, updatedAt INTEGER, UNIQUE(dishId,scope));
CREATE TABLE FamilyMember (id TEXT PRIMARY KEY, role TEXT);
CREATE TABLE FamilySchedule (date INTEGER, memberId TEXT, lunchNotAtHome INTEGER, dinnerNotAtHome INTEGER);
CREATE TABLE WeeklyReview (weekStart INTEGER, referenceDate INTEGER, avoidFoods TEXT);
CREATE TABLE MealPlan (date INTEGER, mealType TEXT, mainDish TEXT, sideDishes TEXT, lunchPlan TEXT, babyMenu TEXT, dinnerDiningOut INTEGER);
INSERT INTO FamilyMember VALUES ('dad','father'),('mom','mother'),('baby','child');
`);
const input = {name: "두부조림",category:"주찬",scope:"family"};
const date = "2026-09-14";
const time = Date.parse(`${date}T00:00:00+09:00`);
const change = {date,main:"두부조림"};
assert.equal(effectiveUsage([]), "UNKNOWN");
assert.throws(() => validatePreference({...input,usage:"yes"}));
assert.throws(() => validatePreference({...input,scope:"everyone",usage:"ALLOW"}));
assert.throws(() => validatePreference({...input,familiarity:null}));
assert.deepEqual(validateMealPreferences(db,[change]), [], "미확인 메뉴는 식단에 넣을 수 있다");
savePreference(db,{...input,familiarity:"FAMILIAR"});
assert.equal(preferenceContext(db)[0].usage, "UNKNOWN", "Familiarity must not grant usage");
savePreference(db,{...input,usage:"ALLOW"});
assert.equal(preferenceContext(db)[0].preferences[0].familiarity,"FAMILIAR", "Partial update preserves familiarity");
assert.deepEqual(validateMealPreferences(db,[change]),[]);
const oneDish = {name: "새우볶음밥",category:"한그릇",scope:"family",usage:"ALLOW"};
savePreference(db, oneDish);
assert.deepEqual(validateMealPreferences(db,[{date,main:"새우볶음밥",mealStyle:"RICE_PORRIDGE_TTEOK"}]), [], "한그릇 식사형태는 한그릇 취향을 확인한다");
assert.deepEqual(validateMealPreferences(db,[{...change,main:"매운 두부조림"}]), [], "다른 이름의 미확인 메뉴도 사용할 수 있다");
assert.equal(preferenceContext(db).find(dish => dish.name === "두부조림").usage, "ALLOW", "미확인 메뉴를 사용해도 기존 취향은 변하지 않는다");
savePreference(db,{...input,scope:"child",usage:"AVOID"});
assert.match(validateMealPreferences(db,[change])[0],/피하는 메뉴/);
db.prepare('INSERT INTO FamilySchedule VALUES (?,?,0,1)').run(time,"baby");
assert.deepEqual(validateMealPreferences(db,[change]),[], "Absent member's preference does not block others");
db.prepare('INSERT INTO WeeklyReview VALUES (?,?,?)').run(time-86_400_000,time,"두부조림");
assert.match(validateMealPreferences(db,[change])[0],/이번 주/);
assert.deepEqual(validateMealPreferences(db,[{...change,date:"2026-09-21"}]).length,1, "Child exclusion still applies next week");
savePreference(db,{...input,scope:"child",usage:"UNKNOWN"});
assert.deepEqual(validateMealPreferences(db,[{...change,date:"2026-09-21"}]),[], "Weekly avoidance expires");
db.prepare('INSERT INTO MealPlan VALUES (?,\'DINNER\',?,\'[]\',\'회사 식사\',NULL,0)').run(time,"두부조림");
savePreference(db,{...input,usage:"AVOID"});
assert.deepEqual(validateMealPreferences(db,[change]),[], "An unchanged saved meal is preserved");
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM MealPlan').get().n,1);
assert.equal(db.prepare('SELECT mainDish FROM MealPlan').get().mainDish,"두부조림", "Preference edits never rewrite meals");
assert.throws(() => savePreference(db,{...input,scope:"stranger",usage:"ALLOW"}));
assert.equal(preferenceContext(db)[0].preferences.find(p => p.scope === "family").source,"chat");
const plan = {date: time,mainDish:"두부조림",sideDishes:"[]",lunchPlan:"회사 식사",dinnerDiningOut:false};
const recipe = {title:"두부조림",category:"주찬",plannedDates:JSON.stringify([date]),instructions:'["조리한다"]',needsReview:false,sourceUrl:"https://example.com",sourceTitle:"테스트",sourceCheckedAt:time,ingredients:[{amount:"200g"}]};
assert.deepEqual(missingRecipeCoverage([plan],[recipe]),[]);
assert.equal(missingRecipeCoverage([plan],[{...recipe,sourceCheckedAt:null}]).length,1);
assert.equal(missingRecipeCoverage([plan],[{...recipe,ingredients:[{amount:"적당량"}]}]).length,1);
assert.equal(missingRecipeCoverage([plan],[{...recipe,needsReview:true}]).length,1);
assert.deepEqual(missingRecipeCoverage([{...plan,dinnerDiningOut:true}],[]),[]);
db.close();
console.log("메뉴 취향 검증 통과: 미확인·익숙함 분리, 부분 수정, 가족/참석 범위, 주간 기피 만료, 메뉴명 구분, 기존 식단 유지, 레시피 누락.");
